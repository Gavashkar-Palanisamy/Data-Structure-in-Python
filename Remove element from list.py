#Remove elements from list in python
lst_1=[1,3,4,5,6,7,8]


#remove:
#remove element of list using value
print(lst_1)
lst_1.remove(6)
print(lst_1)

#remove:
#remove element of list using index
print(lst_1)
lst_1.pop(3)
print(lst_1)

#remove:
#remove element of list using del function
print(lst_1)
del lst_1[2]
print(lst_1)


